export type ThemeKey = 'money' | 'health' | 'protect' | 'love' | 'spirit' | 'work'
export type TourCat = 'temples' | 'practice' | 'journey' | 'rest'
// past — уже проводили (лист ожидания), soon — ближайший выезд, dates — даты по запросу,
// individual — собираем под человека, new — программа в разработке (лист ожидания)
export type TourStatus = 'past' | 'soon' | 'dates' | 'individual' | 'new'

export interface Yagya {
  n: string // название
  god: string // божество
  cat: ThemeKey // тема (категория)
  cl: string // подпись категории
  p: string // назначение
  d: string // ближайшая дата
  pr: string // цена
}

export interface Practice {
  n: string // название
  cat: ThemeKey // тема: оттенок карточки и преднастройка опросника
  cl: string // подпись темы
  who: string // кто ведёт
  p: string // описание
  fmt: string // формат
  dur: string // длительность
  pr: string // цена
}

export interface TourProgram {
  t?: string // заголовок части маршрута (если программа из нескольких частей)
  items: string[]
}

export interface Tour {
  id: string // slug для ссылки /tury?tour=
  n: string
  sub: string // подзаголовок
  cat: TourCat
  cl: string // подпись направления
  status: TourStatus
  d: string // длительность: «11 дней», «7–21 день»; пусто — ещё не утверждена
  pr: string
  prNote?: string // от чего зависит цена
  route: string[] // остановки маршрута по порядку
  img: string // обложка
  pos: string // object-position кадра обложки
  gallery?: string[] // фото из поездки для окна «Подробнее»
  about: string[] // описание для окна «Подробнее»
  focus: string // главный акцент
  program: TourProgram[]
  note?: string // нагрузка и важные условия
}

