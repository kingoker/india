// Русская плюрализация: (n, форма-1, форма-2..4, форма-many)
function plural(n: number, one: string, few: string, many: string): string {
  const m = n % 100
  const d = n % 10
  if (m > 10 && m < 20) return many
  if (d > 1 && d < 5) return few
  if (d === 1) return one
  return many
}

