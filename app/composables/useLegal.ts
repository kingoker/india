/** Подставляет реквизиты оператора в токены {name}, {inn}… */
export function fillOperator(text: string, op: Operator): string {
  return text.replace(/\{(name|inn|ogrnLabel|ogrn|address|email|storage)\}/g, (_, k: keyof Operator) => op[k])
}

export type RichPart = { t: string, href?: string, todo?: boolean }

/** Разбирает [текст](ссылка) и заглушки [в скобках] в части для безопасного рендера. */
export function richParts(text: string, op: Operator): RichPart[] {
  const filled = fillOperator(text, op)
  const parts: RichPart[] = []
  const re = /\[([^\]]+)\]\(([^)]+)\)|\[([^\]]+)\]/g
  let last = 0
  let m: RegExpExecArray | null
  while ((m = re.exec(filled))) {
    if (m.index > last) parts.push({ t: filled.slice(last, m.index) })
    if (m[1]) parts.push({ t: m[1], href: m[2] })
    else parts.push({ t: `[${m[3]}]`, todo: true })
    last = re.lastIndex
  }
  if (last < filled.length) parts.push({ t: filled.slice(last) })
  return parts
}
