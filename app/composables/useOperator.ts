/**
 * Реквизиты оператора персональных данных из runtimeConfig.
 * Не заполнено в .env → подставляется заметная заглушка в [скобках],
 * чтобы пустое поле не ушло в прод незамеченным.
 */
export function useOperator() {
  const op = useRuntimeConfig().public.operator as Record<
    'name' | 'inn' | 'ogrnLabel' | 'ogrn' | 'address' | 'email',
    string
  > & { dbInRu: boolean }

  return {
    name: op.name || '[ИП Фамилия Имя Отчество]',
    inn: op.inn || '[ИНН]',
    ogrnLabel: op.ogrnLabel || 'ОГРНИП',
    ogrn: op.ogrn || '[номер]',
    address: op.address || '[адрес]',
    email: op.email || '[e-mail]',
    /** Где хранятся данные — формулировка зависит от фактического положения дел. */
    storage: op.dbInRu
      ? 'Запись, систематизация, накопление, хранение, уточнение и извлечение персональных данных граждан Российской Федерации выполняются в базах данных, находящихся на территории Российской Федерации (ч. 5 ст. 18 152-ФЗ).'
      : 'Данные хранятся на серверах хостинг-провайдера, которые могут находиться за пределами Российской Федерации. Отправляя форму, вы соглашаетесь с такой передачей и хранением.'
  }
}

export type Operator = ReturnType<typeof useOperator>

/** Значение — ещё заглушка, а не реальный реквизит. */
export const isTodo = (v: string) => v.startsWith('[')
